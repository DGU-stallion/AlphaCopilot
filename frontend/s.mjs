import { chromium } from 'playwright';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1600, height: 950 }, deviceScaleFactor: 2 });
const errs=[]; p.on('pageerror', e=>errs.push(String(e).slice(0,200)));
p.on('console', m=>{ if(m.type()==='error') errs.push('[err] '+m.text().slice(0,120)); });
await p.goto('http://127.0.0.1:5899/daily-review', { waitUntil: 'networkidle' });
await p.waitForTimeout(6000);
await p.screenshot({ path: '/tmp/m2_dark.png' });
console.log('errs:', errs.slice(0,4).join('\n')||'(none)');
await b.close();
